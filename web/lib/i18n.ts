const COL: Record<Lang, number> = { en: 0, pt: 1, es: 2 };
const TABLE = new Map(ENTRIES.map((e) => [e[0], e]));

/** Translate an English UI string into the current language; `{name}` placeholders are filled from vars. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = useTerminal.getState().lang;
  const row = TABLE.get(key);
  let s = row ? row[COL[lang]] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** BCP-47 locale for dates and numbers in the current language. */
export function locale(): string {
  return { pt: "pt-BR", en: "en-US", es: "es-ES" }[useTerminal.getState().lang];
}
